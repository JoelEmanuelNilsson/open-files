local map = vim.keymap.set
local reader = require('reader')
local branches = require('branch-browser')
map({ 'n', 'i', 'v' }, '<C-s>', reader.save_file, { desc = 'Save and return to reading' })
map('n', '<C-z>', 'u', { desc = 'Undo' })
map('i', '<C-z>', '<C-o>u', { desc = 'Undo' })
map('n', '<C-y>', '<C-r>', { desc = 'Redo' })
map('n', '<C-a>', 'ggVG', { desc = 'Select all' })
map('v', '<C-c>', '"+y', { desc = 'Copy' })
map('i', '<C-v>', '<C-r>+', { desc = 'Paste' })
map('n', '<C-f>', '/', { desc = 'Find in this file' })
map('n', '<Esc>', function() if not reader.close_panel() then vim.cmd.nohlsearch() end end, { desc = 'Close panel or clear search' })
for _, key in ipairs({ 'j', '<Down>' }) do map({ 'n', 'v' }, key, "v:count == 0 ? 'gj' : 'j'", { expr = true }) end
for _, key in ipairs({ 'k', '<Up>' }) do map({ 'n', 'v' }, key, "v:count == 0 ? 'gk' : 'k'", { expr = true }) end
map('n', '<leader>e', function() reader.show_sidebar(true) end, { desc = 'Sidebar' })
map('n', '<leader>E', function() require('neo-tree.command').execute({ action = 'show', reveal = true }) end, { desc = 'Reveal this file' })
map('n', '<C-p>', function() reader.search_files('files') end, { desc = 'Find file names' })
map('n', '<leader>f', function() reader.search_files('files') end, { desc = 'Find file names' })
map('n', '<leader>s', function() reader.search_files('grep') end, { desc = 'Search file contents' })
map('n', '<leader>g', branches.choose_branch, { desc = 'Browse branches' })
map('n', '<leader>p', branches.push_branch, { desc = 'Push existing commits' })
map('n', '<leader>i', reader.edit_file, { desc = 'Edit this file' })
map('n', '<leader>a', reader.file_actions, { desc = 'File actions' })
map('n', '<leader>w', reader.close_action, { desc = 'Close a menu or finish editing' })
map('n', '<leader>Q', reader.quit_reader, { desc = 'Quit' })
map('n', '<S-Right>', '<cmd>BufferLineCycleNext<cr>', { desc = 'Next file' })
map('n', '<S-Left>', '<cmd>BufferLineCyclePrev<cr>', { desc = 'Previous file' })
map('n', '<leader><leader>', function()
  local buf = vim.fn.bufnr('#')
  if buf > 0 and vim.bo[buf].buflisted then
    local path = vim.api.nvim_buf_get_name(buf)
    if not reader.view or path:sub(1, #reader.view.root + 1) == reader.view.root .. '/' then reader.open_file(path) end
  end
end, { desc = 'Previous file' })
map('n', '<leader>b', function() Snacks.picker.buffers({ cwd = reader.reading_root(), filter = { cwd = true } }) end, { desc = 'Open files' })
map('n', '<leader>r', function() Snacks.picker.recent({ cwd = reader.reading_root(), filter = { cwd = true } }) end, { desc = 'Recent project files' })
map('n', '<leader>n', function() vim.wo.number = not vim.wo.number end, { desc = 'Line numbers' })
map('n', '<leader>?', reader.open_help, { desc = 'Help' })
map('n', '<F1>', reader.open_help, { desc = 'Help' })
vim.api.nvim_create_user_command('Cheatsheet', reader.open_help, { desc = 'Reader help' })
