#!/usr/bin/env node
/**
 * arc-waypoints — the chrome's hue arc, written out for the status bar.
 *
 *     ./bin/arc-waypoints.mjs > ~/dotfiles/sketchybar/lib/arc.sh
 *
 * The bar wants the same light the prompt box wears, and the only honest way
 * to get it is to ask the thing that defines it. `arcColor` in
 * `extensions/zen-chrome/prism.ts` is the arc as a pure function of position —
 * blue, indigo, violet, magenta, pink, coral, red, gold, yellow, green, with
 * the teal-to-sky wedge excluded — so this samples that and nothing else. A
 * table of hexes typed by hand would be a second definition of the arc, and
 * the second one is the one that goes stale.
 *
 * WHAT THE BAR CANNOT HAVE. pi lights a rail of cells and mixes hues as
 * positions on the arc; sketchybar interpolates one property between two
 * absolute colours in RGB. So the bar gets waypoints and lets sketchybar cut
 * the chord between them. At this spacing the chord costs about 2% of
 * saturation at its midpoint, which is under the 1/255 the channel can carry.
 * Fewer waypoints and that grows as 1-cos(half the hop): by a fifth of the arc
 * per hop it is a visible dip toward grey in the middle of every step.
 *
 * Both surfaces are emitted rather than the current one, because the bar
 * follows the macOS appearance live and a table that only knew about tonight
 * would be wrong at breakfast. `prism.ts` decides what each surface means; the
 * only thing stated here is that there are two of them.
 */

import { dirname, join } from "node:path";

/** Sampling points across the arc, one way. See the chord note above. */
const POINTS = 12;

/**
 * jiti comes from the globally installed pi, because that is the only copy on
 * this machine and the kit declares pi as a peer rather than depending on it.
 * Derived from `process.execPath` rather than written out: the suite files each
 * carry the literal path with a node version in it, and a version bump would
 * break every one of them at once.
 */
const globalModules = join(dirname(process.execPath), "..", "lib", "node_modules");
const { createJiti } = await import(join(globalModules, "@earendil-works/pi-coding-agent/node_modules/jiti/lib/jiti.mjs"));
const kit = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const jiti = createJiti(import.meta.url, { interopDefault: true });

/** sketchybar's format is 0xAARRGGBB, and the alpha is not optional: a six-digit value is invisible. */
const sketchyColor = (rgb) => `0xff${[rgb.r, rgb.g, rgb.b].map((v) => v.toString(16).padStart(2, "0")).join("")}`;

/**
 * The arc as this surface paints it. `PI_ZEN_SURFACE` is prism's own override,
 * and it is the whole reason this can be asked twice in one process: the
 * surface is read per call, not cached at import.
 */
function arc(surface) {
	process.env.PI_ZEN_SURFACE = surface;
	const { arcColor } = jiti(`${kit}/extensions/zen-chrome/prism.ts`);
	return Array.from({ length: POINTS }, (_, i) => sketchyColor(arcColor(i / (POINTS - 1))));
}

const dark = arc("dark");
const light = arc("light");

process.stdout.write(`# Generated by pi/kit/bin/arc-waypoints.mjs -- do not hand-edit.
# The chrome's hue arc, sampled ${POINTS} times from its cold end to its warm one:
# blue, indigo, violet, magenta, pink, coral, red, gold, yellow, green. The one
# thing it never reaches is the wedge from green back round to blue -- teal,
# cyan, sky -- which is what keeps it reading as one light rather than as a
# rainbow.
#
# A fact about the arc, so no timing appears here: how fast a light walks it,
# and how much of it is on screen at once, is the caller's business.
# Regenerate from the pi kit after changing HUE_MIN, HUE_MAX or the surfaces in
# extensions/zen-chrome/prism.ts.
ARC_DARK=(${dark.join(" ")})
ARC_LIGHT=(${light.join(" ")})
ARC_POINTS=${POINTS}
`);
